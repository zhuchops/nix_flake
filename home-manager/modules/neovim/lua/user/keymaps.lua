-- Normal --
-- Better window navigation
keymap("n", "<C-h>", "<C-w>h", opts)
keymap("n", "<C-j>", "<C-w>j", opts)
keymap("n", "<C-k>", "<C-w>k", opts)
keymap("n", "<C-l>", "<C-w>l", opts)

-- Resize with arrows
keymap("n", "<C-Up>", ":resize -2<CR>", opts)
keymap("n", "<C-Down>", ":resize +2<CR>", opts)
keymap("n", "<C-Left>", ":vertical resize -2<CR>", opts)
keymap("n", "<C-Right>", ":vertical resize +2<CR>", opts)

-- Navigate buffers
keymap("n", "<S-l>", ":bnext<CR>", opts)
keymap("n", "<S-h>", ":bprevious<CR>", opts)

-- Move text up and down
keymap("n", "<A-j>", ":m .+1<CR>==", opts)
keymap("n", "<A-k>", ":m .-2<CR>==", opts)

-- Oil mapping for file tree
keymap("n", "<leader>o", ":Oil<CR>")

-- Telescope search (live grep)
keymap("n", "<leader>sg", ":Telescope live_grep<CR>", opts or { desc = "live grep"})

-- Telescope search buffers
keymap("n", "<leader>sb", ":Telescope buffers<CR>", opts )

-- Telescope buffer
keymap("n", "<leader>b", ":Telescope current_buffer_fuzzy_find<CR>", opts)

-- Telescope search commands
keymap("n", "<leader>sc", ":Telescope command_history<CR>", opts)

-- Telescope search files
keymap("n", "<leader>sf", ":Telescope find_files<CR>", opts)

-- Telescope diagnostics
keymap("n", "<leader>d", ":Telescope diagnostics<CR>", opts)

-- Telescope quickfixlist
keymap("n", "<leader>ql", ":Telescope quickfix<CR>", opts)

-- Telescope undo tree
keymap("n", "<leader>u", ":Telescope undo<CR>", opts)


-- Insert --
-- Press jk fast to exit insert mode 
keymap("i", "jk", "<ESC>", opts)
keymap("i", "kj", "<ESC>", opts)

-- Completions
local imap_expr = function(lhs, rhs)
  vim.keymap.set('i', lhs, rhs, { expr = true })
end
imap_expr('<Tab>',   [[pumvisible() ? "\<C-n>" : "\<Tab>"]])
imap_expr('<S-Tab>', [[pumvisible() ? "\<C-p>" : "\<S-Tab>"]])

-- Visual --
-- Stay in indent mode
keymap("v", "<", "<gv^", opts)
keymap("v", ">", ">gv^", opts)

-- Move text up and down
keymap("v", "<A-j>", ":m '>+1<CR>gv=gv", opts)
keymap("v", "<A-k>", ":m '<-2<CR>gv=gv", opts)
keymap("v", "p", '"_dP', opts)

-- Visual Block --
-- Move text up and down
keymap("x", "J", ":m '>+1<CR>gv=gv", opts)
keymap("x", "K", ":m '<-2<CR>gv=gv", opts)
keymap("x", "<A-j>", ":m '>+1<CR>gv=gv", opts)
keymap("x", "<A-k>", ":m '<-2<CR>gv=gv", opts)

